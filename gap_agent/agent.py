"""Command-line entry point: runs the gap-analysis agent (or an offline demo)."""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import date
from pathlib import Path

import anyio

from .catalog import load_catalog
from .report import write_excel, write_markdown
from .store import AssessmentStore

ROOT = Path(__file__).resolve().parent.parent

SYSTEM_PROMPT = """You are a meticulous GRC (governance, risk and compliance) analyst performing a \
gap analysis of an organisation against a security framework.

Method:
1. Call list_controls to get every control in scope, and list_evidence_areas and get_risks for context.
2. For EACH control: search the evidence with one or more targeted queries, then call record_assessment.
3. When done, call get_progress. If any control remains, assess it. Never stop with controls missing.
4. Finish with a short executive summary (max 150 words): overall maturity, the three most urgent gaps and why.

Rules (non-negotiable):
- Ground every judgement in evidence. Only cite evidence IDs returned by search_evidence. Never invent facts.
- Absence of evidence is not evidence of implementation: if nothing supports a control, mark it \
not_implemented and say that no evidence was found.
- Be conservative. Use partially_implemented when something exists but does not meet the requirement.
- confidence = high only when the evidence is direct and unambiguous; otherwise medium or low.
- Recommendations must be concrete and actionable (what, not just "improve X").
- Link gaps to related risks from get_risks when there is a clear connection.
- If record_assessment rejects your input, read the reason, fix it and call it again.
"""


def _run_meta(mode: str, provenance: str, **extra) -> dict:
    return {"date": date.today().isoformat(), "mode": mode, "provenance": provenance, **extra}


def _write_outputs(store: AssessmentStore, out: Path, framework: str, run: dict) -> tuple[Path, Path]:
    md = out / f"gap_analysis_{framework}.md"
    xl = out / f"gap_analysis_{framework}.xlsx"
    write_markdown(store, md, run)
    write_excel(store, xl, run)
    return md, xl


async def run_agent(framework: str, out: Path, model: str | None, max_turns: int, budget: float) -> int:
    from claude_agent_sdk import (AssistantMessage, ClaudeAgentOptions, ClaudeSDKClient,
                                  ResultMessage, TextBlock, ToolUseBlock)

    from .tools import build_server

    if not os.environ.get("ANTHROPIC_API_KEY"):
        print("ANTHROPIC_API_KEY is not set. Export it first, or run with --offline-demo.", file=sys.stderr)
        return 2

    catalog = load_catalog(framework)
    store = AssessmentStore(catalog, audit_path=out / f"audit_log_{framework}.jsonl")
    server, tool_names, _ = build_server(store)

    options = ClaudeAgentOptions(
        system_prompt=SYSTEM_PROMPT,
        mcp_servers={"grc": server},
        tools=[],                      # no built-in tools: no shell, files or web
        allowed_tools=tool_names,      # pre-approve only our six GRC tools
        setting_sources=[],            # ignore any local Claude settings
        max_turns=max_turns,
        max_budget_usd=budget,         # hard cost ceiling
        model=model,
        cwd=str(out),
    )

    prompt = (f"Perform a gap analysis of {catalog.organisation} against {catalog.framework_name}. "
              f"There are {len(catalog.controls)} controls in scope. Assess all of them.")
    summary, result = "", None
    async with ClaudeSDKClient(options=options) as client:
        await client.query(prompt)
        async for msg in client.receive_response():
            if isinstance(msg, AssistantMessage):
                for block in msg.content:
                    if isinstance(block, TextBlock) and block.text.strip():
                        summary = block.text
                        print(f"\n🤖 {block.text.strip()}\n")
                    elif isinstance(block, ToolUseBlock):
                        short = block.name.split("__")[-1]
                        hint = block.input.get("control_id") or block.input.get("query") or ""
                        print(f"   → {short} {hint}")
            elif isinstance(msg, ResultMessage):
                result = msg

    run = _run_meta(
        "live agent run",
        "Generated by a live run of the agent.",
        model=model or "SDK default",
        cost_usd=getattr(result, "total_cost_usd", None),
        turns=getattr(result, "num_turns", None),
        summary=summary,
        summary_label="Executive summary (AI-generated)",
    )
    md, xl = _write_outputs(store, out, framework, run)
    print(f"\nAssessed {len(store.assessments)}/{len(catalog.controls)} controls · "
          f"score {store.compliance_score()}% · rejections {store.rejections}")
    if store.remaining():
        print(f"⚠️  Not assessed: {', '.join(store.remaining())}")
    print(f"Report: {md}\nExcel:  {xl}\nAudit:  {store.audit_path}")
    return 0 if not store.remaining() else 1


async def run_offline_demo(framework: str, out: Path) -> int:
    """Replays hand-written sample assessments through the SAME tool and guardrails
    the agent uses. No API key needed. Demonstrates the pipeline, not the AI."""
    from .tools import build_server

    sample = ROOT / "examples" / f"sample_assessments_{framework}.json"
    if not sample.exists():
        print(f"No sample file for '{framework}' ({sample.name}).", file=sys.stderr)
        return 2
    data = json.loads(sample.read_text(encoding="utf-8"))
    catalog = load_catalog(framework)
    store = AssessmentStore(catalog, audit_path=out / f"audit_log_{framework}.jsonl")
    _, _, tools = build_server(store)
    record = next(t for t in tools if t.name == "record_assessment")
    for a in data["assessments"]:
        res = await record.handler(a)
        status = "REJECTED" if res.get("is_error") else "ok"
        print(f"   → record_assessment {a.get('control_id')}: {status}")
    run = _run_meta("offline demo (no AI)", data.get("provenance", ""), summary=data.get("summary", ""),
                    summary_label="Executive summary (sample, hand-written)")
    md, xl = _write_outputs(store, out, framework, run)
    print(f"\nReport: {md}\nExcel:  {xl}")
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="gap_agent", description="AI-assisted GRC gap analysis agent")
    p.add_argument("--framework", choices=["nis2", "iso27001"], default="nis2")
    p.add_argument("--out", default="output", help="output folder (default: ./output)")
    p.add_argument("--model", default=None, help="Claude model alias or ID, e.g. sonnet or opus")
    p.add_argument("--max-turns", type=int, default=150)
    p.add_argument("--max-budget", type=float, default=5.0, help="hard USD cost ceiling for the run")
    p.add_argument("--offline-demo", action="store_true",
                   help="replay the sample assessments through the guardrails without calling an AI")
    a = p.parse_args(argv)
    out = Path(a.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    if a.offline_demo:
        return anyio.run(run_offline_demo, a.framework, out)
    return anyio.run(run_agent, a.framework, out, a.model, a.max_turns, a.max_budget)
